"""
Stage 2: ORB Feature Detection and Descriptor Extraction Service

Theoretical Background:
ORB stands for "Oriented FAST and Rotated BRIEF":
1. FAST (Features from Accelerated Segment Test):
   A high-speed corner detector evaluating pixel intensity along a Bresenham circle around
   each candidate point. ORB calculates the intensity centroid of the detected corner patch
   to assign a consistent canonical orientation, making the keypoint rotation-invariant.
2. BRIEF (Binary Robust Independent Elementary Features):
   A compact binary descriptor generated by performing pairwise intensity comparisons within
   a local image patch. ORB steers the sample point pairs according to the keypoint's orientation,
   producing a rotation-invariant 256-bit binary descriptor.

Because ORB descriptors are binary bitstrings, similarity between two descriptors is computed
extremely rapidly using Hamming distance (count of differing bits / bitwise XOR followed by bit count).
"""

from typing import List, Tuple, Optional, Dict, Any
import cv2
import numpy as np

from backend.app.core.config import settings


class ImageFeatures:
    """
    Data container holding extracted keypoints and binary descriptors for a single image.
    """
    def __init__(
        self,
        image_index: int,
        filename: str,
        keypoints: List[cv2.KeyPoint],
        descriptors: Optional[np.ndarray],
        image_shape: Tuple[int, int]
    ):
        self.image_index = image_index
        self.filename = filename
        self.keypoints = keypoints
        self.descriptors = descriptors
        self.keypoint_count = len(keypoints) if keypoints is not None else 0
        self.has_descriptors = descriptors is not None and len(descriptors) > 0
        self.image_shape = image_shape


def create_orb_detector(
    n_features: int = settings.ORB_N_FEATURES,
    scale_factor: float = settings.ORB_SCALE_FACTOR,
    n_levels: int = settings.ORB_N_LEVELS,
    edge_threshold: int = settings.ORB_EDGE_THRESHOLD,
    patch_size: int = settings.ORB_PATCH_SIZE
) -> cv2.ORB:
    """
    Creates and configures an OpenCV ORB (Oriented FAST and Rotated BRIEF) detector.
    
    Parameters:
    - n_features: Maximum number of strongest features to retain (default 5000).
    - scale_factor: Pyramid decimation ratio (> 1.0). A factor of 1.2 provides good scale coverage.
    - n_levels: Number of pyramid levels (8 levels yields 1.2^7 ~ 3.58x dynamic range).
    - edge_threshold: Margin size along image boundary where keypoints are not sampled.
    - patch_size: Size of the local patch used to compute the oriented BRIEF descriptor.
    """
    return cv2.ORB_create(
        nfeatures=n_features,
        scaleFactor=scale_factor,
        nlevels=n_levels,
        edgeThreshold=edge_threshold,
        patchSize=patch_size,
        firstLevel=0,
        WTA_K=2,
        scoreType=cv2.ORB_HARRIS_SCORE,
        fastThreshold=20
    )


def extract_orb_features(
    gray_image: np.ndarray,
    image_index: int = 0,
    filename: str = "",
    n_features: int = settings.ORB_N_FEATURES
) -> ImageFeatures:
    """
    Detects keypoints and extracts binary descriptors from a single grayscale image using ORB.
    Handles low-texture images safely without throwing unhandled exceptions.
    """
    h, w = gray_image.shape[:2]
    orb = create_orb_detector(n_features=n_features)
    
    try:
        keypoints, descriptors = orb.detectAndCompute(gray_image, None)
    except Exception as e:
        keypoints, descriptors = [], None

    if keypoints is None:
        keypoints = []
    if descriptors is None:
        descriptors = None

    return ImageFeatures(
        image_index=image_index,
        filename=filename,
        keypoints=list(keypoints),
        descriptors=descriptors,
        image_shape=(h, w)
    )


def extract_features_for_sequence(
    gray_images: List[np.ndarray],
    filenames: List[str],
    n_features: int = settings.ORB_N_FEATURES
) -> List[ImageFeatures]:
    """
    Extracts ORB features for all images in the sequence.
    """
    features_list: List[ImageFeatures] = []
    for idx, (gray, fname) in enumerate(zip(gray_images, filenames)):
        feats = extract_orb_features(gray, image_index=idx, filename=fname, n_features=n_features)
        features_list.append(feats)
    return features_list


def detect_and_compute_features(
    image_bgr: np.ndarray, method: str = "SIFT", max_features: int = 2500
) -> Tuple[List[cv2.KeyPoint], Optional[np.ndarray]]:
    """
    Extracts scale- and rotation-invariant keypoints and descriptors from an image.
    Uses SIFT by default with fallback to ORB.
    """
    if len(image_bgr.shape) == 3:
        gray = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2GRAY)
    else:
        gray = image_bgr
    if method.upper() == "SIFT":
        try:
            sift = cv2.SIFT_create(nfeatures=max_features)
            kps, des = sift.detectAndCompute(gray, None)
            return kps if kps is not None else [], des
        except Exception:
            pass
    orb = cv2.ORB_create(nfeatures=max_features)
    kps, des = orb.detectAndCompute(gray, None)
    return kps if kps is not None else [], des



def detect_and_compute_features(
    image_bgr: np.ndarray, method: str = "ORB", max_features: int = settings.ORB_N_FEATURES
) -> Tuple[List[cv2.KeyPoint], Optional[np.ndarray]]:
    """
    Convenience helper extracting ORB keypoints and descriptors from a BGR or Gray image.
    """
    if len(image_bgr.shape) == 3:
        gray = cv2.cvtColor(image_bgr, cv2.COLOR_BGR2GRAY)
    else:
        gray = image_bgr
    feats = extract_orb_features(gray, n_features=max_features)
    return feats.keypoints, feats.descriptors
